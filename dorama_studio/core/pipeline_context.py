"""
Pipeline Context - Shared state object passed between all agents in the orchestration.
Ensures Single Source of Truth and typed contracts between agents.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime


@dataclass
class PipelineContext:
    """
    Immutable-ish context that flows through the agent pipeline.
    Each agent receives a copy, mutates what it owns, and returns the updated context.
    """

    # Project identification
    project_id: str
    project_name: str
    genre: str
    concept_seed: str
    total_episodes: int

    # Current episode being processed
    episode_num: int = 1
    episode_id: str = ""

    # Character bible (loaded from persistence)
    characters: list[dict] = field(default_factory=list)

    # Episode blueprint (from StoryArchitect)
    episode_blueprint: dict = field(default_factory=dict)

    # Beats generated by MasterWriter
    beats: list[dict] = field(default_factory=list)

    # Visual prompts from VideoAnimator/VideoAgent
    visual_prompts: list[dict] = field(default_factory=list)

    # Video generation results
    video_results: list[dict] = field(default_factory=list)

    # Audio prompts from audio agents
    audio_prompts: list[dict] = field(default_factory=list)

    # Quality gate results
    quality_results: dict = field(default_factory=dict)

    # Continuity snapshots
    continuity_snapshots: list[dict] = field(default_factory=list)

    # Distribution metadata
    distribution_schedule: list[dict] = field(default_factory=list)

    # Analytics & feedback
    analytics_data: dict = field(default_factory=dict)
    feedback_hypotheses: list[str] = field(default_factory=list)

    # Trends data from TrendHunterAgent
    trends_data: dict = field(default_factory=dict)

    # Metadata
    created_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())
    updated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())
    version: int = 1

    # Error tracking
    errors: list[dict] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> PipelineContext:
        return cls(**data)

    def update_timestamp(self):
        self.updated_at = datetime.utcnow().isoformat()
        self.version += 1

    def add_error(self, agent: str, message: str, recoverable: bool = True):
        self.errors.append(
            {
                "agent": agent,
                "message": message,
                "recoverable": recoverable,
                "timestamp": datetime.utcnow().isoformat(),
            }
        )

    def add_warning(self, message: str):
        self.warnings.append(message)

    def merge_into_context(self, result: AgentResult) -> PipelineContext:
        """Apply result.context_updates to the pipeline context"""
        for key, value in result.context_updates.items():
            if hasattr(self, key):
                setattr(self, key, value)
            else:
                # Allow dynamic fields
                object.__setattr__(self, key, value)
        self.update_timestamp()
        return self


@dataclass
class AgentResult:
    """Standardized result from any agent execution"""

    success: bool
    agent_name: str
    output_data: dict = field(default_factory=dict)
    context_updates: dict = field(
        default_factory=dict
    )  # Fields to merge into PipelineContext
    logs: list[dict] = field(default_factory=list)  # Generation logs for persistence
    error: str = ""
    recoverable: bool = True
    latency_ms: int = 0
    tokens_used: int = 0
    model_used: str = ""
